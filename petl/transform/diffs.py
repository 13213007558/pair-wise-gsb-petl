"""
Generate and apply diffs (patches) between tables.

"""

from __future__ import absolute_import, print_function, division


from collections import Counter

from petl.compat import next, text_type
from petl.comparison import comparable_itemgetter
from petl.util.base import Table, asindices
from petl.transform.sorts import sort


class PatchConflict(Exception):
    """Raised when a patch cannot be applied because the table being
    patched no longer matches the state the patch was generated from.

    The `conflicts` attribute is a list of human readable strings, one
    per conflicting row or key.

    """

    def __init__(self, conflicts):
        if isinstance(conflicts, text_type):
            conflicts = [conflicts]
        self.conflicts = list(conflicts)

    def __str__(self):
        return 'patch cannot be applied, conflicting changes detected: ' \
            + '; '.join(self.conflicts)


class TablePatch(object):
    """A materialised, applicable difference between two tables, as
    generated by :func:`tablediff`.

    Attributes:

    - `key`: tuple of field names identifying rows
    - `source_header`: header of the source table at diff time
    - `target_header`: header of the target table at diff time
    - `added_fields`: fields present in the target but not the source
    - `removed_fields`: fields present in the source but not the target
    - `ops`: list of operations, each one of
      `('add', record, count)`, `('delete', record, count)` or
      `('update', key, old_record, new_record)` where records are
      dictionaries mapping field names to values

    """

    def __init__(self, key, source_header, target_header, ops):
        self.key = tuple(key)
        self.source_header = tuple(source_header)
        self.target_header = tuple(target_header)
        self.ops = list(ops)

    @property
    def added_fields(self):
        return tuple(f for f in self.target_header
                     if f not in self.source_header)

    @property
    def removed_fields(self):
        return tuple(f for f in self.source_header
                     if f not in self.target_header)

    def apply(self, table):
        """Return a table like `table` with this patch applied. See
        :func:`applypatch`."""
        return AppliedPatchView(table, self)

    def __len__(self):
        return len(self.ops)

    def __repr__(self):
        return 'TablePatch(key=%r, ops=%r)' % (self.key, self.ops)


def tablediff(source, target, key, buffersize=None, tempdir=None,
              cache=True):
    """
    Generate an applicable patch transforming the `source` table into the
    `target` table. Rows are identified by the given `key` field(s). E.g.::

        >>> import petl as etl
        >>> source = [['id', 'name', 'qty'],
        ...           [1, 'apples', 3],
        ...           [2, 'bananas', 7],
        ...           [3, 'pears', 1]]
        >>> target = [['id', 'name', 'qty'],
        ...           [1, 'apples', 4],
        ...           [3, 'pears', 1],
        ...           [4, 'figs', 9]]
        >>> patch = etl.tablediff(source, target, key='id')
        >>> patch.ops
        [('update', (1,), {'id': 1, 'name': 'apples', 'qty': 3}, {'id': 1, 'name': 'apples', 'qty': 4}), ('delete', {'id': 2, 'name': 'bananas', 'qty': 7}, 1), ('add', {'id': 4, 'name': 'figs', 'qty': 9}, 1)]
        >>> etl.applypatch(source, patch)
        +----+----------+-----+
        | id | name     | qty |
        +====+==========+=====+
        |  1 | 'apples' |   4 |
        +----+----------+-----+
        |  3 | 'pears'  |   1 |
        +----+----------+-----+
        |  4 | 'figs'   |   9 |
        +----+----------+-----+

    If the key uniquely identifies rows in both tables, differing rows
    sharing a key are reported as field-level modifications (`update`
    operations carrying the expected old record and the new record). If a
    key occurs more than once on either side, rows under that key are
    compared as a multiset of whole records, and the difference is
    reported as `add` and `delete` operations with multiplicities -
    rows sharing a key are never arbitrarily paired up into updates.

    Field order may differ between the two tables; records are matched by
    field name. A missing column is not the same thing as a column whose
    value is `None`. Columns added or removed between the two tables
    are reflected in the patch via the `added_fields` and
    `removed_fields` attributes and in the records carried by the
    operations.

    The patch carries expected pre-application values (for updates and
    deletes) and multiplicities, so that :func:`applypatch` can detect
    conflicting changes made to the table after the patch was generated,
    instead of silently overwriting them.

    Both tables are read exactly once: they are sorted on the key using
    the (external) sort implementation of
    :func:`petl.transform.sorts.sort`, see the discussion of the
    `buffersize`, `tempdir` and `cache` arguments there.

    .. versionadded:: 1.7.27

    """

    sa = sort(source, key=key, buffersize=buffersize, tempdir=tempdir,
              cache=cache)
    sb = sort(target, key=key, buffersize=buffersize, tempdir=tempdir,
              cache=cache)
    return _diff_sorted(sa, sb, key)


Table.tablediff = tablediff


def applypatch(table, patch):
    """
    Apply a `patch` generated by :func:`tablediff` to `table`, returning
    a new table. E.g.::

        >>> import petl as etl
        >>> source = [['id', 'qty'], [1, 3], [2, 7]]
        >>> target = [['id', 'qty'], [1, 4], [2, 7]]
        >>> patch = etl.tablediff(source, target, key='id')
        >>> etl.applypatch(source, patch).lookall()
        +----+-----+
        | id | qty |
        +====+=====+
        |  1 |   4 |
        +----+-----+
        |  2 |   7 |
        +----+-----+

    Applying a patch to a table that has changed since the patch was
    generated raises :class:`PatchConflict` describing the specific
    conflicting rows, rather than silently overwriting the changes, e.g.,
    if someone modified a value in the meantime::

        >>> changed = [['id', 'qty'], [1, 99], [2, 7]]
        >>> etl.applypatch(changed, patch).lookall()
        Traceback (most recent call last):
        ...
        petl.transform.diffs.PatchConflict: patch cannot be applied, conflicting changes detected: row with key (1,) has changed: field 'qty': expected 3, found 99

    Rows added to the table in the meantime are preserved; only
    modifications or removals of rows the patch expects to find, and
    rows the patch cannot account for, are conflicts.

    .. versionadded:: 1.7.27

    """

    return AppliedPatchView(table, patch)


Table.applypatch = applypatch


class AppliedPatchView(Table):

    def __init__(self, source, patch):
        self.source = source
        self.patch = patch

    def __iter__(self):
        return _iterapply(self.source, self.patch)


def _diff_sorted(sa, sb, key):
    ita = iter(sa)
    itb = iter(sb)
    try:
        ha = tuple(next(ita))
    except StopIteration:
        ha = ()
    try:
        hb = tuple(next(itb))
    except StopIteration:
        hb = ()
    idxa = asindices(ha, key)
    idxb = asindices(hb, key)
    keyfields = tuple(ha[i] for i in idxa)
    geta = comparable_itemgetter(*idxa)
    getb = comparable_itemgetter(*idxb)
    ops = list()
    for _key, rowsa, rowsb in _merge_groups(ita, itb, geta, getb):
        ops.extend(_diff_group(keyfields, ha, hb, rowsa, rowsb))
    return TablePatch(keyfields, ha, hb, ops)


def _groups(it, getkey):
    # group consecutive rows sharing the same key
    key = None
    rows = list()
    for row in it:
        k = getkey(row)
        if rows and k != key:
            yield key, rows
            rows = list()
        rows.append(tuple(row))
        key = k
    if rows:
        yield key, rows


def _merge_groups(ita, itb, geta, getb):
    ga = _groups(ita, geta)
    gb = _groups(itb, getb)
    a = next(ga, None)
    b = next(gb, None)
    while a is not None or b is not None:
        if a is None:
            yield b[0], [], b[1]
            b = next(gb, None)
        elif b is None:
            yield a[0], a[1], []
            a = next(ga, None)
        elif a[0] < b[0]:
            yield a[0], a[1], []
            a = next(ga, None)
        elif b[0] < a[0]:
            yield b[0], [], b[1]
            b = next(gb, None)
        else:
            yield a[0], a[1], b[1]
            a = next(ga, None)
            b = next(gb, None)


def _diff_group(keyfields, ha, hb, rowsa, rowsb):
    ops = list()
    if len(rowsa) == 1 and len(rowsb) == 1:
        # unique identity on both sides, report field modifications
        old = dict(zip(ha, rowsa[0]))
        new = dict(zip(hb, rowsb[0]))
        if old != new:
            keyvals = tuple(old[f] for f in keyfields)
            ops.append(('update', keyvals, old, new))
        return ops
    # duplicated identity, compare rows as a multiset
    counts_a = Counter()
    counts_b = Counter()
    records = dict()
    for row in rowsa:
        rec = dict(zip(ha, row))
        fr = _freeze_record(rec)
        counts_a[fr] += 1
        records.setdefault(fr, rec)
    for row in rowsb:
        rec = dict(zip(hb, row))
        fr = _freeze_record(rec)
        counts_b[fr] += 1
        records.setdefault(fr, rec)
    for fr in sorted(set(counts_a) | set(counts_b), key=repr):
        na = counts_a[fr]
        nb = counts_b[fr]
        if na > nb:
            ops.append(('delete', records[fr], na - nb))
        elif nb > na:
            ops.append(('add', records[fr], nb - na))
    return ops


def _iterapply(source, patch):
    it = iter(source)
    try:
        hdr = tuple(next(it))
    except StopIteration:
        hdr = ()
    # the set of fields must not have changed since the diff was made
    missing = [f for f in patch.source_header if f not in hdr]
    unexpected = [f for f in hdr if f not in patch.source_header]
    if missing or unexpected:
        conflicts = list()
        if missing:
            conflicts.append('fields removed since diff: %r'
                             % (missing,))
        if unexpected:
            conflicts.append('fields added since diff: %r'
                             % (unexpected,))
        raise PatchConflict(conflicts)
    # index the patch operations
    updates = dict()
    deletes = Counter()
    delete_records = dict()
    adds = list()
    for op in patch.ops:
        if op[0] == 'update':
            _, keyvals, old, new = op
            updates[_freeze(keyvals)] = (keyvals, old, new)
        elif op[0] == 'delete':
            _, rec, n = op
            fr = _freeze_record(rec)
            deletes[fr] += n
            delete_records.setdefault(fr, rec)
        else:
            _, rec, n = op
            adds.append((rec, n))
    expected_deletes = Counter(deletes)
    used = set()
    conflicts = list()
    thdr = patch.target_header
    yield thdr
    for row in it:
        rec = dict(zip(hdr, row))
        k = _freeze(tuple(rec.get(f) for f in patch.key))
        if k in updates:
            keyvals, old, new = updates[k]
            if k in used:
                conflicts.append('key %r matches more than one row'
                                 % (keyvals,))
                continue
            used.add(k)
            if rec != old:
                conflicts.append(_update_conflict(keyvals, old, rec))
                continue
            out = new
        else:
            fr = _freeze_record(rec)
            if deletes.get(fr):
                deletes[fr] -= 1
                continue
            out = rec
        try:
            yield tuple(out[f] for f in thdr)
        except KeyError:
            conflicts.append('row %r is not accounted for by the patch'
                             % (rec,))
    for k, (keyvals, old, new) in updates.items():
        if k not in used:
            conflicts.append('no row found with key %r, expected %r'
                             % (keyvals, old))
    for fr, remaining in deletes.items():
        if remaining:
            conflicts.append(
                'expected %d copies of row %r, found %d'
                % (expected_deletes[fr], delete_records[fr],
                   expected_deletes[fr] - remaining))
    if conflicts:
        raise PatchConflict(conflicts)
    for rec, n in adds:
        outrow = tuple(rec[f] for f in thdr)
        for _ in range(n):
            yield outrow


def _update_conflict(keyvals, expected, actual):
    details = list()
    for f in sorted(set(expected) | set(actual), key=text_type):
        if f not in actual:
            details.append('field %r: expected %r, found missing'
                           % (f, expected[f]))
        elif f not in expected:
            details.append('field %r: expected missing, found %r'
                           % (f, actual[f]))
        elif expected[f] != actual[f]:
            details.append('field %r: expected %r, found %r'
                           % (f, expected[f], actual[f]))
    return 'row with key %r has changed: %s' % (keyvals, '; '.join(details))


def _freeze_record(rec):
    # hashable, order-independent representation of a record, preserving
    # the distinction between a missing field and a value of None
    return tuple((k, _freeze(v))
                 for k, v in sorted(rec.items(),
                                    key=lambda kv: text_type(kv[0])))


def _freeze(value):
    if isinstance(value, tuple):
        return ('t', tuple(_freeze(v) for v in value))
    if isinstance(value, list):
        return ('l', tuple(_freeze(v) for v in value))
    if isinstance(value, dict):
        return ('d', tuple(sorted(((_freeze(k), _freeze(v))
                                   for k, v in value.items()),
                                  key=repr)))
    if isinstance(value, (set, frozenset)):
        return ('s', tuple(sorted((_freeze(v) for v in value), key=repr)))
    try:
        hash(value)
    except TypeError:
        return ('r', repr(value))
    return value
